// Photographs the editor in its main states, to judge its look.
import { mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
// Pictures go to scripts/look/out/. Run `npm run build` first.
const out = fileURLToPath(new URL('./out/', import.meta.url)).replace(/\\/g, '/');
mkdirSync(out, { recursive: true });
const EDITOR = new URL('../../dist-editor/editor.html', import.meta.url).href;
const PLAYER = new URL('../../dist/index.html', import.meta.url).href;
import { launch, openPage, sleep } from '../lib.mjs';
const browser = await launch();
const { page, errors } = await openPage(browser, EDITOR, { viewport: { width: 1500, height: 950 } });
const click = (text, within = 'body') => page.evaluate((t, w) => [...document.querySelectorAll(`${w} button`)].find((b) => b.textContent.includes(t))?.click(), text, within);
await page.evaluate(() => new Promise((done) => { const r = indexedDB.deleteDatabase('editor'); r.onsuccess = r.onerror = r.onblocked = done; }));
await page.reload();
await page.waitForFunction(() => window.__game && window.__editor, { timeout: 20000 });
await sleep(600);
await page.screenshot({ path: `${out}ed-0-start.png` });
const open = async (tab) => {
  await page.click('button[data-library="objects"]');
  await page.waitForSelector('.modal');
  if (tab) await page.click(`.modal [data-library-tab="${tab}"]`);
  await sleep(400);
};
await open();
await page.screenshot({ path: `${out}ed-1-library.png` });
await page.click('.modal [data-library-tab="parts"]');
await sleep(300);
await page.screenshot({ path: `${out}ed-2-parts.png` });
await page.click('.modal button[data-block="key-door"]');
await page.waitForFunction(() => !document.querySelector('.modal'));
await open('roles');
await page.click('.modal button[data-block="jump-player"]');
await page.waitForFunction(() => !document.querySelector('.modal'));
await sleep(500);
await page.screenshot({ path: `${out}ed-3-object.png` });
await click('قانون‌ها', '.tabs');
await sleep(300);
await page.evaluate(() => document.querySelector('.rule-closed')?.click());
await sleep(300);
await page.screenshot({ path: `${out}ed-4-rules.png` });
await page.keyboard.press('Escape');
await page.evaluate(() => window.__editor && document.querySelector('.phone-screen')?.dispatchEvent(new MouseEvent('click')));
await click('بازی', '.tabs');
await sleep(300);
await page.evaluate(() => document.querySelector('[data-item]')?.scrollIntoView({ block: 'center' }));
await sleep(200);
await page.screenshot({ path: `${out}ed-5-game.png` });
await click('امتحان کن');
await sleep(1500);
await page.screenshot({ path: `${out}ed-6-play.png` });
console.log(errors);
await browser.close();
